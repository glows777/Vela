import { appendFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'
import type { ModelPricing } from '../../shared/pricing.ts'
import type { ProviderUsage } from '../../shared/provider-types.ts'
import { toolResultOutputToText } from '../context/tool-result-output.ts'
import {
  estimateMessagesTokens,
  estimateTextTokens,
  IMAGE_TOKENS,
  isImageContentPart,
  type ModelMessage,
  stripOpaqueFields,
} from '../messages.ts'

export type { ModelPricing }

/** The offline demo model (`VELA_MODEL=mock`) is priced like Claude Haiku 4.5 so the demo shows costs */
const MOCK_PRICING: ModelPricing = {
  input: 1.0,
  output: 5.0,
  cacheWrite: 1.25,
  cacheRead: 0.1,
}

export interface StepUsage {
  /** Uncached input tokens, billed at the normal input price. */
  inputTokens: number
  /** Output tokens generated by the model. */
  outputTokens: number
  /** Input tokens that hit an existing prompt cache. */
  cacheReadTokens: number
  /** Input tokens written to the prompt cache by this request. */
  cacheWriteTokens: number
}

export interface StepRecord extends StepUsage {
  kind?: 'main' | 'summary' | 'dream'
  usage?: ProviderUsage
  durationMs?: number
  /** Unix timestamp when this model request finished. */
  ts: number
  /** Model id used for this request. */
  model: string
  /** Cost of this request in USD; undefined when the model has no known price. */
  cost?: number
}

export interface UsageTotals {
  /** Total uncached input tokens. */
  inputTokens: number
  /** Total output tokens. */
  outputTokens: number
  /** Total cache read tokens. */
  cacheReadTokens: number
  /** Total cache write tokens. */
  cacheWriteTokens: number
  /** Total actual cost of the priced requests; undefined when no request had a known price. */
  cost?: number
  /** cache read / all input-like tokens. */
  hitRate: number
  /** Cost if every input-like token had missed the cache; undefined like `cost`. */
  baselineCost?: number
  /** Cost saved compared with no cache; undefined like `cost`. */
  savedCost?: number
  /** Number of recorded model requests. */
  steps: number
}

export interface TokenStatus {
  /** Estimated tokens in the current context. */
  tokens: number
  /** Current context as a percentage of the fixed window. */
  percent: number
  /** Whether the threshold for context defense actions is reached. */
  needsAction: boolean
}

/** Model context window size; the shared threshold base for status and defense. */
export const CONTEXT_WINDOW = 200_000

/**
 * Tracks token state at two different scopes:
 *
 * 1. Current context estimate: used by defense / compaction;
 * 2. Usage and cost of each model request: used by /usage.
 *
 * One object manages both, but they never share a number.
 */
export class TokenTracker {
  /** Snapshot used by the session usage inspector; callers cannot mutate recent records. */
  snapshot() {
    const last = this.recent(1)[0]
    return {
      ...this.status,
      totals: this.totals(),
      contextWindow: this.contextWindow,
      ...(last ? { lastRecord: { ...last } } : {}),
    }
  }

  /** Usage details of each successful model request, accumulated across agentLoops. */
  private steps: StepRecord[] = []
  /** Optional JSONL usage log path. */
  private logPath?: string
  /** Full context token count from the last API response (inputTokens + outputTokens). */
  private lastPreciseCount = 0
  /** Prompt+output tokens of the latest response, while the estimate is anchored to a provider report. */
  private reportedPromptTokens?: number
  /** Weighted token estimate of messages added since the last API calibration. */
  private pendingTokens = 0
  /** Baseline active tool definition tokens at the last API calibration. */
  private baselineToolTokens?: number
  /** Current active tool definition tokens. */
  private currentToolTokens = 0
  /** Additional token delta introduced by context hooks when preparing a request. */
  private contextHookDeltaTokens = 0
  /** Context hook token delta already included in the latest calibrated API usage. */
  private baselineContextHookDeltaTokens = 0
  /** Price from the current model config (cost in models.json); overrides the built-in table and updates on model switch. */
  private pricing?: ModelPricing
  /** Sum of each step's hypothetical no-cache cost, at the price in effect at request time (old requests are not repriced after a model switch). */
  private baselineCost = 0
  /** Whether any recorded request had a known price. */
  private priced = false
  /** Current model's context window, used for the status percentage. */
  contextWindow = CONTEXT_WINDOW

  constructor(logPath?: string) {
    this.logPath = logPath
    if (logPath) mkdirSync(dirname(logPath), { recursive: true })
  }

  /** Calibrates the current context baseline with `inputTokens + outputTokens` from the API. */
  updateFromAPI(
    inputTokens: number,
    outputTokens = 0,
    toolTokens?: number,
  ): void {
    const total = Math.max(0, inputTokens + outputTokens)
    this.reportedPromptTokens = total
    this.lastPreciseCount = total
    this.pendingTokens = 0
    this.baselineContextHookDeltaTokens = this.contextHookDeltaTokens
    if (toolTokens !== undefined) {
      this.baselineToolTokens = toolTokens
      this.currentToolTokens = toolTokens
    }
  }

  /** Tracks active tool schema tokens so newly discovered tools update the reported estimate. */
  syncToolTokens(toolTokens: number): void {
    this.currentToolTokens = toolTokens
    if (
      this.reportedPromptTokens !== undefined &&
      this.baselineToolTokens === undefined
    )
      this.baselineToolTokens = toolTokens
  }

  /** Tracks net token delta from extension context hooks relative to raw session history. */
  setContextDelta(deltaTokens: number): void {
    this.contextHookDeltaTokens = deltaTokens
  }

  /** Net token delta from extension context hooks since the last API usage calibration. */
  get contextDelta(): number {
    return this.reportedPromptTokens !== undefined
      ? this.contextHookDeltaTokens - this.baselineContextHookDeltaTokens
      : this.contextHookDeltaTokens
  }

  /** Builds a local context estimate (e.g. from loaded history); the request estimate is used until a provider reports usage. */
  setEstimatedTokens(tokens: number): void {
    this.reportedPromptTokens = undefined
    this.lastPreciseCount = Math.max(0, tokens)
    this.pendingTokens = 0
    this.baselineToolTokens = undefined
    this.contextHookDeltaTokens = 0
    this.baselineContextHookDeltaTokens = 0
  }

  /** Adds a new message's estimated tokens to the current context. */
  addMessage(message: ModelMessage): void {
    this.pendingTokens += countMessageTokens(message)
  }

  /** Adds several new messages' estimated tokens to the current context. */
  addMessages(messages: ModelMessage[]): void {
    for (const message of messages) {
      this.addMessage(message)
    }
  }

  /** Adjusts the context estimate by the token difference before and after replacing messages. */
  replaceMessages(before: ModelMessage[], after: ModelMessage[]): void {
    this.pendingTokens +=
      countMessagesTokens(after) - countMessagesTokens(before)
  }

  /** Current context token estimate: last API baseline plus local message, tool, and hook deltas. */
  get estimatedTokens(): number {
    const toolDelta =
      this.reportedPromptTokens !== undefined &&
      this.baselineToolTokens !== undefined
        ? Math.max(0, this.currentToolTokens - this.baselineToolTokens)
        : 0
    return Math.max(
      0,
      this.lastPreciseCount +
        this.pendingTokens +
        toolDelta +
        this.contextDelta,
    )
  }

  /**
   * Context size for thresholds: the prompt tokens the provider reported for the latest response plus the
   * local estimate of messages added since. Undefined before any provider report; callers then use their own
   * request estimate.
   */
  get reportedContextTokens(): number | undefined {
    return this.reportedPromptTokens === undefined
      ? undefined
      : this.estimatedTokens
  }

  /**
   * Switches to the model with this window and price (undefined uses the built-in table). Its tokenizer may
   * count differently, so the previous model's reported prompt size is dropped: thresholds fall back to the
   * local request estimate until this model reports usage. Only later requests are priced with it.
   */
  setModel(contextWindow: number, pricing: ModelPricing | undefined): void {
    this.contextWindow = contextWindow
    this.pricing = pricing
    this.reportedPromptTokens = undefined
    this.baselineContextHookDeltaTokens = 0
  }

  /** Current context status relative to the model window (default 200k). */
  get status(): TokenStatus {
    const tokens = this.estimatedTokens
    const percent = Math.round((tokens / this.contextWindow) * 100)
    return {
      tokens,
      percent,
      needsAction: percent >= 75,
    }
  }

  /**
   * Records one model request.
   */
  record(
    model: string,
    usage: StepUsage,
    details: Pick<StepRecord, 'kind' | 'usage' | 'durationMs'> = {
      kind: 'main',
    },
    capturedPricing?: { value: ModelPricing | undefined },
  ): StepRecord {
    const price =
      (capturedPricing ? capturedPricing.value : this.pricing) ??
      (model === 'mock-model' ? MOCK_PRICING : undefined)
    let cost: number | undefined
    if (price) {
      cost = computeCost(usage, price)
      const inputLike =
        usage.inputTokens + usage.cacheReadTokens + usage.cacheWriteTokens
      this.baselineCost +=
        (inputLike * price.input + usage.outputTokens * price.output) /
        1_000_000
      this.priced = true
    }
    const record: StepRecord = {
      ts: Date.now(),
      model,
      ...(cost === undefined ? {} : { cost }),
      ...usage,
      ...details,
    }
    this.steps.push(record)

    if (this.logPath) {
      appendFileSync(this.logPath, `${JSON.stringify(record)}\n`)
    }
    return record
  }

  /** Returns total usage, cache and cost over this tracker's lifetime. */
  totals(): UsageTotals {
    const t = this.steps.reduce(
      (a, s) => ({
        inputTokens: a.inputTokens + s.inputTokens,
        outputTokens: a.outputTokens + s.outputTokens,
        cacheReadTokens: a.cacheReadTokens + s.cacheReadTokens,
        cacheWriteTokens: a.cacheWriteTokens + s.cacheWriteTokens,
        cost: a.cost + (s.cost ?? 0),
      }),
      {
        inputTokens: 0,
        outputTokens: 0,
        cacheReadTokens: 0,
        cacheWriteTokens: 0,
        cost: 0,
      },
    )
    const totalInputLike =
      t.inputTokens + t.cacheReadTokens + t.cacheWriteTokens
    const hitRate = totalInputLike > 0 ? t.cacheReadTokens / totalInputLike : 0
    // Hypothetical no-cache cost: pay full price for every input-like token as a miss
    const { cost, ...tokens } = t
    if (!this.priced) return { ...tokens, hitRate, steps: this.steps.length }
    const baselineCost = this.baselineCost
    return {
      ...tokens,
      cost,
      hitRate,
      baselineCost,
      savedCost: baselineCost - cost,
      steps: this.steps.length,
    }
  }

  /** Returns recent model request records without changing totals. */
  recent(n: number): StepRecord[] {
    return this.steps.slice(-n)
  }
}

function countMessageTokens(message: ModelMessage): number {
  if (typeof message.content === 'string') {
    return estimateTextTokens(message.content)
  }
  if (!Array.isArray(message.content)) return 0

  let tokens = 0
  for (const part of message.content) {
    if (isImageContentPart(part)) {
      tokens += IMAGE_TOKENS
    } else if ('text' in part && typeof part.text === 'string') {
      tokens += estimateTextTokens(part.text)
    } else if ('output' in part) {
      const output = part.output
      if (output.type === 'content') {
        tokens += output.value.reduce(
          (total, item) =>
            total +
            (isImageContentPart(item)
              ? IMAGE_TOKENS
              : item.type === 'text'
                ? estimateTextTokens(item.text)
                : estimateTextTokens(
                    toolResultOutputToText({ type: 'content', value: [item] }),
                  )),
          0,
        )
      } else if (output.type === 'json') {
        tokens += estimateTextTokens(
          JSON.stringify(stripOpaqueFields(output.value)) ?? '',
        )
      } else {
        tokens += estimateTextTokens(toolResultOutputToText(output))
      }
    } else if ('input' in part) {
      tokens += estimateTextTokens(
        JSON.stringify(stripOpaqueFields(part.input)) ?? '',
      )
    }
  }
  return tokens
}

function countMessagesTokens(messages: ModelMessage[]): number {
  let tokens = 0
  for (const message of messages) {
    tokens += countMessageTokens(message)
  }
  return tokens
}

/** Estimates history tokens from message content, for context defense. */
export function estimateMessageTokens(messages: ModelMessage[]): number {
  return estimateMessagesTokens(messages)
}

function computeCost(usage: StepUsage, p: ModelPricing): number {
  return (
    (usage.inputTokens * p.input +
      usage.outputTokens * p.output +
      usage.cacheReadTokens * p.cacheRead +
      usage.cacheWriteTokens * p.cacheWrite) /
    1_000_000
  )
}

/**
 * Normalizes the AI SDK usage object into four token kinds.
 *
 * The AI SDK splits input tokens in `inputTokenDetails` into uncached, cache read and cache write.
 * Its `inputTokens` is the total of all three; this keeps the tracker's four-kind billing scheme,
 * so `StepUsage.inputTokens` means uncached input tokens.
 */
export function normalizeUsage(usage: ProviderUsage | undefined): StepUsage {
  if (!usage)
    return {
      inputTokens: 0,
      outputTokens: 0,
      cacheReadTokens: 0,
      cacheWriteTokens: 0,
    }

  const cacheReadTokens = usage.inputTokenDetails?.cacheReadTokens ?? 0
  const cacheWriteTokens = usage.inputTokenDetails?.cacheWriteTokens ?? 0
  const inputTokens =
    usage.inputTokenDetails?.noCacheTokens ??
    Math.max(0, (usage.inputTokens ?? 0) - cacheReadTokens - cacheWriteTokens)

  return {
    inputTokens: Math.max(0, inputTokens),
    outputTokens: usage.outputTokens ?? 0,
    cacheReadTokens,
    cacheWriteTokens,
  }
}
