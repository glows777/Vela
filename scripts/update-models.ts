/**
 * Regenerates packages/core/src/models/catalog.generated.ts from pi's model catalog (the `@earendil-works/pi-ai` npm package,
 * MIT, built from models.dev plus pi's corrections). Only the providers and fields Vela uses are kept.
 *
 *   bun scripts/update-models.ts [version]   (default: the version pinned below)
 */
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const PI_AI_VERSION = process.argv[2] ?? '1.1.0'

/** Wire protocols Vela speaks through the AI SDK */
const APIS = ['anthropic-messages', 'openai-responses', 'openai-completions']

/**
 * Providers whose models go into the catalog. The first three are built in; the rest only lend metadata
 * (context window, price, thinking) to models.json providers that use the same model ids.
 */
const PROVIDERS = [
  'anthropic',
  'openai',
  'openrouter',
  'deepseek',
  'xai',
  'groq',
  'cerebras',
  'moonshotai',
  'zai',
  'minimax',
]

const FIELDS = [
  'id',
  'name',
  'api',
  'reasoning',
  'input',
  'cost',
  'contextWindow',
  'maxTokens',
  'thinkingLevelMap',
] as const

const work = mkdtempSync(join(tmpdir(), 'vela-models-'))
try {
  const meta = (await (
    await fetch(
      `https://registry.npmjs.org/@earendil-works/pi-ai/${PI_AI_VERSION}`,
    )
  ).json()) as { dist: { tarball: string } }
  const tarball = join(work, 'pi-ai.tgz')
  await Bun.write(tarball, await fetch(meta.dist.tarball))
  await Bun.$`tar xzf ${tarball} -C ${work}`.quiet()

  const lines: string[] = []
  let count = 0
  for (const provider of PROVIDERS) {
    const file = join(
      work,
      'package',
      'dist',
      'providers',
      'data',
      `${provider}.json`,
    )
    const data = JSON.parse(readFileSync(file, 'utf-8')) as Record<
      string,
      Record<string, Record<string, unknown>>
    >
    const models: Record<string, unknown>[] = []
    for (const api of APIS)
      for (const model of Object.values(data[api] ?? {})) {
        if (model.type !== 'chat') continue
        const entry: Record<string, unknown> = {}
        for (const field of FIELDS)
          if (model[field] !== undefined) entry[field] = model[field]
        const cost = entry.cost as Record<string, number> | undefined
        if (cost)
          entry.cost = {
            input: cost.input,
            output: cost.output,
            cacheRead: cost.cacheRead,
            cacheWrite: cost.cacheWrite,
          }
        models.push(entry)
      }
    models.sort((a, b) => String(a.id).localeCompare(String(b.id)))
    count += models.length
    lines.push(
      `  ${JSON.stringify(provider)}: [\n${models.map((m) => `    ${JSON.stringify(m)},`).join('\n')}\n  ],`,
    )
  }

  const source = `// Generated by scripts/update-models.ts from @earendil-works/pi-ai@${PI_AI_VERSION} (MIT). Do not edit by hand.
import type { CatalogModel } from './catalog.ts'

export const MODEL_CATALOG: Record<string, CatalogModel[]> = {
${lines.join('\n')}
}
`
  await Bun.write(
    join(
      import.meta.dir,
      '..',
      'packages',
      'core',
      'src',
      'models',
      'catalog.generated.ts',
    ),
    source,
  )
  console.log(
    `Wrote ${count} models from ${PROVIDERS.length} providers (pi-ai ${PI_AI_VERSION})`,
  )
} finally {
  rmSync(work, { recursive: true, force: true })
}
