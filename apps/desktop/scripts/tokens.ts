import { resolve } from 'node:path'
import tokens from '../design/tokens.json'

const root = resolve(import.meta.dir, '..')
const declarations = Object.entries(tokens.tokens)
type Theme = (typeof tokens.themes)[number]
const valueFor = (value: string | Record<Theme, string>, theme: Theme) =>
  typeof value === 'string' ? value : value[theme]
for (const [name, value] of declarations) {
  if (!/^vela-[a-z][a-z0-9-]*$/.test(name))
    throw new Error(`Vela token must use the vela- prefix: ${name}`)
  for (const theme of tokens.themes) {
    if (!valueFor(value, theme))
      throw new Error(`Missing ${theme} value for ${name}`)
  }
}
const themeBlock = (theme: Theme) =>
  declarations
    .filter(([, value]) => theme === 'light' || typeof value !== 'string')
    .map(([name, value]) => `  --${name}: ${valueFor(value, theme)};`)
    .join('\n')
const fonts = tokens.fonts
  .map(
    (font) =>
      `@font-face {\n  font-family: ${font.family};\n  src: url("../assets/${font.file}") format("woff2");\n  font-weight: ${font.weight};\n  font-style: ${font.style};\n  font-display: swap;\n}`,
  )
  .join('\n\n')
const output = `/* Generated by bun run tokens. Edit design/tokens.json. */\n${fonts}\n\n:root, :root[data-theme="light"] {\n${themeBlock('light')}\n}\n\n:root[data-theme="dark"] {\n${themeBlock('dark')}\n}\n\n:root[data-theme="high-contrast"] {\n${themeBlock('high-contrast')}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${themeBlock('dark')}\n  }\n}\n\n@media (prefers-contrast: more), (forced-colors: active) {\n  :root:not([data-theme]) {\n${themeBlock('high-contrast')}\n  }\n}\n`
const target = resolve(root, 'src/styles/tokens.generated.css')
if (process.argv.includes('--check')) {
  if ((await Bun.file(target).text()) !== output)
    throw new Error('Token CSS drift. Run bun run --cwd apps/desktop tokens.')
  console.log(
    `Vela tokens match. ${declarations.length} prefixed declarations, three themes.`,
  )
} else {
  await Bun.write(target, output)
  console.log(
    `Generated ${declarations.length} prefixed brand declarations in three themes.`,
  )
}
